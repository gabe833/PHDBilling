// bills, distributions and renewals: money and dates by property, no bank or tenant details
// files attached to a bill (the vendor's invoice): only an id, a file name and a link, wherever MagicDoor keeps them
const FILE_KEY = /(file|attach|document|upload|invoice|receipt|image|photo)/i;
function findFiles(x: unknown, depth = 0, out: { id: string; name: string; url: string }[] = []) {
  if (!x || typeof x !== "object" || depth > 3) return out;
  for (const [k, v] of Object.entries(x as Obj)) {
    if (!v || typeof v !== "object" || !FILE_KEY.test(k)) { if (v && typeof v === "object" && k === "lineItems") (v as Obj[]).forEach((li) => findFiles(li, depth + 1, out)); continue; }
    const list = Array.isArray(v) ? v : [v];
    for (const f of list as Obj[]) {
      if (!f || typeof f !== "object") continue;
      const url = S(f.url || f.fileUrl || f.downloadUrl || f.signedUrl || f.link || f.uri || f.path || "");
      const id = S(f.id || f.fileId || f.attachmentId || f.documentId || "");
      const name = S(f.name || f.fileName || f.filename || f.originalName || f.originalFileName || f.title || f.description || "").slice(0, 160);
      if (id || /^https?:/.test(url)) out.push({ id, name, url: /^https?:/.test(url) ? url : "" });
      else findFiles(f, depth + 1, out);
    }
  }
  return out;
}
function cleanBill(x: Obj, vendors: Record<string, string>, accounts: Record<string, string>) {
  return {
    files: findFiles(x).slice(0, 10), ref: S(x.reference || x.billNumber || x.invoiceNumber || x.number || "").slice(0, 60),
    id: S(x.id), date: D(x.billDate), due: D(x.dueDate), status: S(x.status), company: B(x.companyBill),
    vendor: vendors[S(x.vendorId)] || "", memo: S(x.memo).slice(0, 200), total: N(x.totalAmount), owed: N(x.dueAmount),
    // who entered it in MagicDoor (a staff id, resolved to a name from MagicDoor's team list when it's available) and when
    by: S(((x.creator || {}) as Obj).propertyManagerId || ((x.creator || {}) as Obj).id), byType: S(((x.creator || {}) as Obj).type), bySource: S(((x.creator || {}) as Obj).source).slice(0, 40), created: S(x.created).slice(0, 19),
    lines: ((x.lineItems as Obj[]) || []).map((li) => ({ id: S(li.id), propertyId: S(li.propertyId), amount: N(li.amount), text: S(li.description).slice(0, 200), account: accounts[S(li.chartOfAccountId)] || "" })),
  };
}
function cleanDistribution(x: Obj) {
  return {
    id: S(x.id), date: D(x.distributionDate), ownerId: S(x.ownerId), total: N(x.totalAmount), memo: S(x.memo).slice(0, 200),
    // where the payout stands in MagicDoor (a payout stuck "pending" hasn't reached the owner)
    // MagicDoor gives no status on a payout: it's paid once nothing is left due on it and a payment (not voided) is applied
    status: (() => {
      const due = N(x.dueAmount) || 0, lines = ((x.lineItems as Obj[]) || []), allocs = lines.flatMap((li) => ((li.allocations as Obj[]) || []));
      const live = allocs.filter((a) => !a.voided && a.applied);
      if (due > 0.004) return live.length ? "partly paid" : (allocs.length ? "failed" : "pending");
      return "paid";
    })(),
    lines: ((x.lineItems as Obj[]) || []).map((li) => ({ propertyId: S(li.propertyId), amount: N(li.amount), text: S(li.description).slice(0, 120) })),
  };
}
function cleanRenewal(x: Obj) {
  const newRent = ((x.recurringChargeChanges as Obj[]) || []).reduce((a, c) => a + (N(c.newAmount) || 0), 0);
  return { id: S(x.id), leaseId: S(x.leaseId), propertyId: S(x.propertyId), unitId: S(x.unitId), status: S(x.status), newEnd: D(x.newEndDate), finalized: B(x.finalized), newRent: newRent || null };
}
// A lease ledger, summed by month (amounts only — no tenant, bank or payment-method details):
//   rent        rent charged (Rent Income)            other     other charges the owner keeps
//   filters / lateFee / applications / phd           charges PHD keeps (MagicDoor "company" charges and late fees)
//   credits     credits given to the tenant           paid      payments that cleared    pending   payments still processing
function ledgerMonths(body: Obj, accounts: Record<string, string>, from: string) {
  const out: Record<string, Record<string, number>> = {};
  const names: Record<string, string> = { ...accounts };
  ((body.chartOfAccounts as Obj[]) || []).forEach((a) => { names[S(a.id)] = S(a.name); });
  const add = (m: string, k: string, v: number) => { const o = out[m] = out[m] || {}; o[k] = Math.round(((o[k] || 0) + v) * 100) / 100; };
  for (const e of ((body.entries as Obj[]) || [])) {
    const m = S(D(e.transactionDate) || "").slice(0, 7); if (!m || m < from) continue;
    const st = S(e.status).toLowerCase(), type = S(e.type), amt = Math.abs(N(e.amount) || 0);
    if (!amt || /void|deleted|cancel|reversed/.test(st)) continue;
    const acct = names[S(((e.chartOfAccountIds as unknown[]) || [])[0])] || "";
    if (type === "payment") { if (st === "settled" || st === "paid" || st === "completed") add(m, "paid", amt); else if (!/fail|return|declin/.test(st)) add(m, "pending", amt); continue; }
    if (type === "credit") { add(m, "credits", amt); continue; }
    if (type === "lateFee" || /late/i.test(acct)) { add(m, "lateFee", amt); continue; }
    if (type !== "charge") continue;
    if (B(e.companyCharge)) add(m, /filter|hvac/i.test(acct + " " + S(e.description)) ? "filters" : /applic/i.test(acct) ? "applications" : "phd", amt);
    else add(m, S(((e.chartOfAccountIds as unknown[]) || [])[0]) === "410000" || /^rent/i.test(acct) ? "rent" : "other", amt);
  }
  return out;
}
// One property's owner statement for one month — MagicDoor's own account of what the owner is paid.
// Amounts only: tenants' names are never kept (their rent is one total); vendor names and descriptions are.
//   begin / end    cash held for the owner at the start / end of the month
//   rentIn         what tenants paid that counts for the owner this month
//   fees           management fees (PM fee, and a leasing fee when there is one)
//   bills / admin  vendor bills paid, and PHD's admin-fee lines on them
//   dists          payouts to the owner        other   anything else (owner contributions, refunds), signed
const r2 = (n: number) => Math.round(n * 100) / 100;
function cleanStatement(e: Obj) {
  const s = (e.summary || {}) as Obj;
  const out = {
    begin: N(s.beginningCashBalance) || 0, end: N(s.endingCashBalance) || 0, cashIn: N(s.cashIn) || 0, cashOut: N(s.cashOut) || 0,
    contrib: N(s.ownerContributions) || 0, distTotal: N(s.ownerDistributions) || 0, unpaid: N(s.unpaidBills) || 0, net: N(s.netOwnerFunds),
    rentIn: 0, fees: [] as number[], bills: [] as { d: string | null; v: string; t: string; a: number }[], admin: [] as { d: string | null; t: string; a: number }[],
    dists: [] as { d: string | null; a: number }[], other: [] as { d: string | null; k: string; t: string; a: number }[],
    pre: null as number | null, left: null as number | null, deposits: 0,
  };
  for (const t of ((e.transactions as Obj[]) || [])) {
    const k = S(t.entityType), inn = N(t.cashIn) || 0, outv = N(t.cashOut) || 0, party = (t.partyInfo || {}) as Obj, d = D(t.date), desc = S(t.description).slice(0, 160);
    if (k === "leaseCharge") { out.rentIn = r2(out.rentIn + inn - outv); continue; }
    if (k === "managementFee") { out.fees.push(r2(outv - inn)); continue; }
    if (k === "ownerDistribution") { out.dists.push({ d, a: r2(outv - inn) }); continue; }
    if (k === "vendorBill") {
      const v = S(party.type) === "vendor" ? S(party.name).slice(0, 80) : "";
      if (/\badmin(istrative)?\s*fee\b/i.test(desc)) out.admin.push({ d, t: desc, a: r2(outv - inn) });
      else out.bills.push({ d, v, t: desc, a: r2(outv - inn) });
      continue;
    }
    // security deposits moving in or out are held for the tenant, not the owner's money for the month
    if (k === "ledgerTransfer" || /deposit/i.test(S(t.sourceType)) || /SecurityDeposit/i.test(desc)) { out.deposits = r2((out.deposits || 0) + inn - outv); continue; }
    out.other.push({ d, k, t: S(party.type) === "tenant" ? "" : desc, a: r2(inn - outv) });
  }
  // bills not paid yet: the owner statement already takes them off what the owner is owed
  for (const u of ((e.unpaidBills as Obj[]) || [])) {
    const a = r2(N(u.dueAmount ?? u.amount ?? u.totalAmount ?? u.cashOut) || 0); if (!a) continue;
    const desc = S(u.description || u.memo || u.name).slice(0, 160), v = S(((u.vendor || u.partyInfo || {}) as Obj).name || u.vendorName).slice(0, 80), d = D(u.billDate || u.date || u.dueDate);
    if (/\badmin(istrative)?\s*fee\b/i.test(desc)) out.admin.push({ d, t: desc, a, unpaid: true } as never);
    else out.bills.push({ d, v, t: desc, a, unpaid: true } as never);
  }
  return out;
}
