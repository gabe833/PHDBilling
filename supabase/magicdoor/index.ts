// PHD Billing — MagicDoor connector (Supabase Edge Function "magicdoor")
// ---------------------------------------------------------------------
// Reads MagicDoor (read-only) and saves a cleaned snapshot the console uses:
// properties, units, leases (rent, balance, days past due, last payment,
// deposits, tenants' names and contact details), owners, management fees,
// vendor bills, owner distributions and lease renewals — then applies it to the console's
// property records (the same update code the console runs, in engine.js).
//
// Never saved: Social Security numbers, dates of birth, bank details, or any
// field not on the allow-list below. Nothing is ever written to MagicDoor.
//
// Modes (POST body {mode}):
//   ping      check the key works                         (Team members)
//   sync      read MagicDoor and save the snapshot        (Team members, or the hourly schedule)
//   discover  field-name report, no values                (Team members)
//   probe     field-name report for more addresses        (Team members)
//
// Secrets (Edge Functions → Secrets):  MAGICDOOR_API_KEY
// Supabase provides SUPABASE_URL, SUPABASE_ANON_KEY and SUPABASE_SERVICE_ROLE_KEY.

// @ts-ignore — plain JavaScript module generated by build.py (the console's own update code)
import { runApply } from "./engine.js";

const AUTH_URL = "https://auth.magicdoor.com/api-keys/token";
const API = "https://api.portal.magicdoor.com";

const cors = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};
const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { ...cors, "Content-Type": "application/json" } });

type Obj = Record<string, unknown>;
const S = (v: unknown) => (v == null ? "" : String(v));
const N = (v: unknown) => (v == null || v === "" || isNaN(Number(v)) ? null : Number(v));
const D = (v: unknown) => (typeof v === "string" && /^\d{4}-\d{2}-\d{2}/.test(v) ? v.slice(0, 10) : null);
const B = (v: unknown) => v === true;

// ---------- MagicDoor sign-in (token lasts ~15 min; renewed a minute early) ----------
let token = "", tokenUntil = 0;
async function mdToken(): Promise<string> {
  if (token && Date.now() < tokenUntil) return token;
  const key = (Deno.env.get("MAGICDOOR_API_KEY") || "").trim();
  if (!key) throw new Error("MAGICDOOR_API_KEY is not set in Edge Functions → Secrets");
  const r = await fetch(AUTH_URL, {
    method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ key }), signal: AbortSignal.timeout(20000),
  });
  if (r.status === 401) throw new Error("MagicDoor rejected the key (401). It may be mistyped, revoked or expired, or its owner was deactivated.");
  if (!r.ok) throw new Error(`MagicDoor sign-in failed: ${r.status}`);
  const d = await r.json();
  if (!d.accessToken) throw new Error("MagicDoor sign-in returned no token");
  token = d.accessToken;
  tokenUntil = Date.now() + Math.max(60, Number(d.expiresIn || 900) - 60) * 1000;
  return token;
}
async function mdGet(path: string): Promise<{ status: number; body: unknown; text: string }> {
  for (let attempt = 0; ; attempt++) {
    const t = await mdToken();
    const r = await fetch(API + path, { headers: { Authorization: "Bearer " + t, Accept: "application/json" }, signal: AbortSignal.timeout(25000) });
    if (r.status === 401 && attempt === 0) { token = ""; continue; }                     // token expired early: sign in again once
    if ((r.status === 429 || r.status >= 500) && attempt < 2) { await new Promise((ok) => setTimeout(ok, 1500 * (attempt + 1))); continue; }
    const text = await r.text();
    let body: unknown = null;
    try { body = JSON.parse(text); } catch { /* not JSON */ }
    return { status: r.status, body, text };
  }
}

// Lists come back 50 at a time with currentPage / totalPages. The page parameter's name
// isn't documented, so the first multi-page list finds out which one MagicDoor honours.
// MagicDoor's page order isn't stable (a record can show up on two pages and another on none),
// so records are kept by id and the pages are read again until every record has been seen.
let pageParam = "";
async function listAll(path: string, onPage?: (body: Obj) => void, maxPages = 60): Promise<Obj[]> {
  const first = await mdGet(path);
  if (first.status !== 200) throw new Error(`MagicDoor ${path} answered ${first.status}`);
  const b = first.body as Obj;
  const seen = new Map<string, Obj>();
  const keep = (body: Obj) => { if (onPage) onPage(body); (((body?.items) as Obj[]) || []).forEach((it, i) => seen.set(S(it.id) || `${path}#${seen.size}-${i}`, it)); };
  keep(b);
  const total = Math.min(Number(b?.totalPages || 1), maxPages), want = Number(b?.totalCount || 0);
  if (total <= 1) return [...seen.values()];
  const sep = path.includes("?") ? "&" : "?";
  if (!pageParam) {
    for (const p of ["page", "pageNumber", "currentPage", "pageIndex"]) {
      const r = await mdGet(`${path}${sep}${p}=2`);
      if (r.status === 200 && Number((r.body as Obj)?.currentPage) === 2) { pageParam = p; break; }
    }
    if (!pageParam) throw new Error(`Couldn't page through ${path} (only the first ${seen.size} of ${want} came back)`);
  }
  for (let pass = 0; pass < 3; pass++) {
    const pages: number[] = []; for (let pg = pass === 0 ? 2 : 1; pg <= total; pg++) pages.push(pg);
    const worker = async () => {
      while (pages.length) {
        const pg = pages.shift()!;
        const r = await mdGet(`${path}${sep}${pageParam}=${pg}`);
        if (r.status !== 200) throw new Error(`MagicDoor ${path} page ${pg} answered ${r.status}`);
        keep(r.body as Obj);
      }
    };
    await Promise.all([worker(), worker(), worker(), worker()]);
    if (!want || seen.size >= want) break;
  }
  return [...seen.values()];
}

// ---------- the allow-list: exactly what gets saved ----------
const addr = (a: unknown) => {
  const o = (a || {}) as Obj;
  return { street: [S(o.streetAddress1), S(o.streetAddress2)].filter(Boolean).join(" "), city: S(o.city), state: S(o.state), zip: S(o.zipCode) };
};
const personName = (o: Obj) => [S(o.firstName), S(o.lastName)].filter(Boolean).join(" ").trim();

function cleanProperty(p: Obj) {
  return {
    id: S(p.id), name: S(p.displayName || p.name), type: S(p.type), active: p.active !== false,
    addr: addr(p.address), portfolioId: S(p.portfolioId), portfolio: S(((p.portfolio || {}) as Obj).name),
    unitCount: N(p.unitCount), defaultUnitId: S(((p.defaultUnit || {}) as Obj).id),
    owners: ((p.owners as Obj[]) || []).map((x) => ({ id: S(((x.owner || {}) as Obj).id), pct: N(x.ownershipPercentage) })).filter((x) => x.id),
  };
}
function cleanUnit(u: Obj) {
  return {
    id: S(u.id), propertyId: S(u.propertyId), name: S(u.name), line: S(u.singleLineAddress), addr: addr(u.address),
    active: u.active !== false, marketRent: N(u.marketRent), beds: N(u.beds), baths: N(u.baths),
    activeLeaseIds: ((u.activeLeases as Obj[]) || []).map((l) => S(l.id)),
  };
}
function cleanLease(l: Obj) {
  return {
    id: S(l.id), propertyId: S(l.propertyId), unitId: S(l.unitId), unitName: S(((l.unit || {}) as Obj).name),
    start: D(l.start), end: D(l.end), ended: B(l.ended), monthToMonth: B(l.monthToMonth), eviction: B(l.eviction), draft: B(l.draft),
    status: S(l.status), rent: N(l.currentRent), balance: N(l.balance), postedBalance: N(l.postedBalance), pastDueDays: N(l.pastDueDays),
    lastPayment: D(l.lastPaymentDate), unpaidSince: D(l.earliestUnpaidBillDueDate),
    depositPaid: N(l.securityDepositPaid), depositRequested: N(l.securityDepositRequested), depositDue: N(l.securityDepositDue),
    tenants: ((l.tenants as Obj[]) || []).map((t) => {
      const p = (t.tenant || {}) as Obj;                       // ssn, dateOfBirth, currentAddress are deliberately not read
      return { id: S(p.id), name: personName(p), email: S(p.email), phone: S(p.phone), moveIn: D(t.moveIn), movedOut: B(t.isMovedOut) };
    }),
  };
}
function cleanOwner(o: Obj) {
  return {
    id: S(o.id), name: personName(o), isCompany: B(o.isCompany), email: S(o.email), phone: S(o.phone), addr: addr(o.address), active: o.active !== false,
    properties: ((o.ownerProperties as Obj[]) || []).map((x) => ({ propertyId: S(x.propertyId), pct: N(x.ownershipPercentage) })),
  };
}

// bills, distributions and renewals: money and dates by property, no bank or tenant details
function cleanBill(x: Obj, vendors: Record<string, string>, accounts: Record<string, string>) {
  return {
    id: S(x.id), date: D(x.billDate), due: D(x.dueDate), status: S(x.status), company: B(x.companyBill),
    vendor: vendors[S(x.vendorId)] || "", memo: S(x.memo).slice(0, 200), total: N(x.totalAmount), owed: N(x.dueAmount),
    lines: ((x.lineItems as Obj[]) || []).map((li) => ({ id: S(li.id), propertyId: S(li.propertyId), amount: N(li.amount), text: S(li.description).slice(0, 200), account: accounts[S(li.chartOfAccountId)] || "" })),
  };
}
function cleanDistribution(x: Obj) {
  return {
    id: S(x.id), date: D(x.distributionDate), ownerId: S(x.ownerId), total: N(x.totalAmount), memo: S(x.memo).slice(0, 200),
    lines: ((x.lineItems as Obj[]) || []).map((li) => ({ propertyId: S(li.propertyId), amount: N(li.amount), text: S(li.description).slice(0, 120) })),
  };
}
function cleanRenewal(x: Obj) {
  const newRent = ((x.recurringChargeChanges as Obj[]) || []).reduce((a, c) => a + (N(c.newAmount) || 0), 0);
  return { id: S(x.id), leaseId: S(x.leaseId), propertyId: S(x.propertyId), unitId: S(x.unitId), status: S(x.status), newEnd: D(x.newEndDate), finalized: B(x.finalized), newRent: newRent || null };
}
const nameOf = (v: Obj) => S(v.name || v.companyName || v.displayName) || personName(v);

async function sync() {
  const t0 = Date.now();
  const props = await listAll("/company-app/properties");
  const units = await listAll("/company-app/units");
  const leases = await listAll("/company-app/leases");
  const owners = await listAll("/company-app/owners");
  // management fees: total per property per month (by the period they cover), last 15 months
  const cutoff = new Date(); cutoff.setMonth(cutoff.getMonth() - 15);
  const cut = cutoff.toISOString().slice(0, 7);
  const feeMap: Record<string, number> = {};
  const notes: string[] = [];
  try {
    for (const f of await listAll("/company-app/management-fees")) {
      const month = S(D(f.periodStart) || D(f.chargeDate)).slice(0, 7);
      if (!month || month < cut) continue;
      for (const li of (f.lineItems as Obj[]) || []) {
        const k = S(li.propertyId) + "|" + month;
        feeMap[k] = Math.round(((feeMap[k] || 0) + (N(li.amount) || 0)) * 100) / 100;
      }
    }
  } catch (e) { notes.push("Management fees: " + String((e as Error).message || e)); }
  // chart of accounts (names for bill lines), vendor bills and owner distributions — last 15 months
  const accounts: Record<string, string> = {}, vendors: Record<string, string> = {};
  let bills: ReturnType<typeof cleanBill>[] = [], dists: ReturnType<typeof cleanDistribution>[] = [], renewals: ReturnType<typeof cleanRenewal>[] = [];
  try {
    const r = await mdGet("/company-app/chart-of-accounts");
    if (r.status === 200 && Array.isArray(r.body)) (r.body as Obj[]).forEach((a) => accounts[S(a.id)] = S(a.name));
  } catch (e) { notes.push("Chart of accounts: " + String((e as Error).message || e)); }
  const cutDay = cut + "-01";
  try {
    const raw = await listAll("/company-app/vendors/bills", (body) => ((body.vendors as Obj[]) || []).forEach((v) => vendors[S(v.id)] = nameOf(v)));
    bills = raw.map((x) => cleanBill(x, vendors, accounts)).filter((x) => x.date && x.date >= cutDay && x.status !== "voided" && x.status !== "rejected");
  } catch (e) { notes.push("Vendor bills: " + String((e as Error).message || e)); }
  try { dists = (await listAll("/company-app/owners/distributions")).map(cleanDistribution).filter((x) => x.date && x.date >= cutDay); }
  catch (e) { notes.push("Owner distributions: " + String((e as Error).message || e)); }
  try { renewals = (await listAll("/company-app/leases/renewals")).map(cleanRenewal); }
  catch (e) { notes.push("Renewals: " + String((e as Error).message || e)); }
  const keepEnded = new Date(Date.now() - 120 * 864e5).toISOString().slice(0, 10);   // ended leases kept 120 days (deposit returns)
  const snap = {
    v: 1, syncedAt: new Date().toISOString(),
    properties: props.map(cleanProperty),
    units: units.map(cleanUnit),
    leases: leases.map(cleanLease).filter((l) => !l.draft && (!l.ended || (l.end && l.end >= keepEnded))),
    owners: owners.map(cleanOwner),
    fees: Object.entries(feeMap).map(([k, amount]) => { const [propertyId, month] = k.split("|"); return { propertyId, month, amount }; }),
    bills, distributions: dists, renewals,
    notes, took: 0,
  };
  snap.took = Math.round((Date.now() - t0) / 100) / 10;
  await saveSnapshot(snap);
  let applied: unknown = null;
  try { applied = await applyToConsole(snap); } catch (e) { notes.push("Updating the console: " + String((e as Error).message || e)); }
  return { ok: true, syncedAt: snap.syncedAt, counts: { properties: snap.properties.length, units: snap.units.length, leases: snap.leases.length, owners: snap.owners.length, fees: snap.fees.length, bills: bills.length, distributions: dists.length, renewals: renewals.length }, took: snap.took, applied, notes };
}

// one document, shared/magicdoor, written with the service key (the console only reads it)
async function saveSnapshot(snap: unknown) {
  const url = Deno.env.get("SUPABASE_URL")!, srv = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") || "";
  if (!srv) throw new Error("SUPABASE_SERVICE_ROLE_KEY isn't available to the function");
  const r = await fetch(url + "/rest/v1/docs?on_conflict=kind,id", {
    method: "POST",
    headers: { apikey: srv, Authorization: "Bearer " + srv, "Content-Type": "application/json", Prefer: "resolution=merge-duplicates,return=minimal" },
    body: JSON.stringify({ kind: "shared", id: "magicdoor", data: snap, deleted: false }),
  });
  if (!r.ok) throw new Error("Saving the MagicDoor snapshot failed: " + r.status + " " + (await r.text()).slice(0, 200));
}

// ---------- apply the snapshot to the console's records (same code the console runs) ----------
// Reads the console's property records, runs the update (tenants, leases, rent, owners, bills, payouts,
// one row per MagicDoor unit), and saves only what changed. Each save carries the version it was based on,
// so a record someone is editing at that moment is skipped and picked up next time.
function srvHeaders(extra: Record<string, string> = {}) {
  const srv = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") || "";
  return { apikey: srv, Authorization: "Bearer " + srv, "Content-Type": "application/json", ...extra };
}
async function rest(path: string, init: RequestInit = {}) {
  const r = await fetch(Deno.env.get("SUPABASE_URL")! + "/rest/v1/" + path, init);
  if (!r.ok) throw new Error(`${init.method || "GET"} ${path.split("?")[0]} → ${r.status} ${(await r.text()).slice(0, 160)}`);
  return r;
}
type Doc = { kind: string; id: string; data: Obj; version: number };
async function loadDocs(): Promise<Doc[]> {
  const out: Doc[] = [];
  for (let from = 0; ; from += 1000) {
    const r = await rest("docs?select=kind,id,data,version&deleted=is.false&or=(kind.in.(pm_property,pm_row,pm_meta,pm_deposit),and(kind.eq.shared,id.in.(main,mdlinks)))&order=kind,id",
      { headers: srvHeaders({ "Range-Unit": "items", Range: `${from}-${from + 999}` }) });
    const page = await r.json() as Doc[];
    out.push(...page);
    if (page.length < 1000) break;
  }
  return out;
}
function todayNY() {
  const p = new Intl.DateTimeFormat("en-CA", { timeZone: "America/New_York", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
  return p;                                                                   // YYYY-MM-DD
}
async function applyToConsole(snap: Obj) {
  const docs = await loadDocs();
  const before = new Map<string, Doc>(docs.map((d) => [d.kind + "/" + d.id, d]));
  const main = before.get("shared/main"), links = before.get("shared/mdlinks");
  const state: Obj & { pm: { properties: Obj[]; rows: Record<string, Obj>; meta: Record<string, Obj>; deposits: Record<string, Obj> } } = {
    pm: { properties: [], rows: {}, meta: {}, deposits: {} },
    owners: structuredClone((main?.data?.owners as Obj[]) || []),
    md: snap,
    mdLinks: structuredClone(links?.data || { links: {}, ignore: {}, auto: true, appliedAt: "", log: [] }),
  };
  for (const d of docs) {
    const v = structuredClone(d.data);
    if (d.kind === "pm_property") state.pm.properties.push(v);
    else if (d.kind === "pm_row") state.pm.rows[d.id] = v;
    else if (d.kind === "pm_meta") state.pm.meta[d.id] = v;
    else if (d.kind === "pm_deposit") state.pm.deposits[d.id] = v;
  }
  if (!state.pm.properties.length) return { changes: 0, note: "no properties yet" };
  const changes = runApply(state, todayNY());
  if (!changes && (state.mdLinks as Obj).appliedAt === (links?.data as Obj | undefined)?.appliedAt) return { changes: 0 };
  // what the records look like now
  const after = new Map<string, Obj>();
  state.pm.properties.filter((p) => !p.deleted).forEach((p) => after.set("pm_property/" + p.id, p));
  Object.entries(state.pm.rows).forEach(([k, r]) => after.set("pm_row/" + k, r));
  Object.entries(state.pm.meta).forEach(([k, m]) => after.set("pm_meta/" + k, m));
  Object.entries(state.pm.deposits).forEach(([k, d]) => after.set("pm_deposit/" + k, d));
  if (main) after.set("shared/main", { ...main.data, owners: state.owners });
  after.set("shared/mdlinks", state.mdLinks as Obj);
  const ops: (() => Promise<string>)[] = [];
  for (const [key, data] of after) {
    const [kind, ...rest2] = key.split("/"), id = rest2.join("/"), old = before.get(key);
    if (!old) ops.push(async () => { await rest("docs", { method: "POST", headers: srvHeaders({ Prefer: "return=minimal" }), body: JSON.stringify({ kind, id, data }) }); return "added"; });
    else if (JSON.stringify(old.data) !== JSON.stringify(data)) ops.push(async () => {
      const r = await rest(`docs?kind=eq.${kind}&id=eq.${encodeURIComponent(id)}&version=eq.${old.version}`, { method: "PATCH", headers: srvHeaders({ Prefer: "return=representation" }), body: JSON.stringify({ data }) });
      return (await r.json() as unknown[]).length ? "updated" : "skipped";      // someone saved it a moment ago: next sync
    });
  }
  for (const [key, old] of before) {
    if (after.has(key) || !/^pm_/.test(old.kind)) continue;
    ops.push(async () => {
      const r = await rest(`docs?kind=eq.${old.kind}&id=eq.${encodeURIComponent(old.id)}&version=eq.${old.version}`, { method: "PATCH", headers: srvHeaders({ Prefer: "return=representation" }), body: JSON.stringify({ deleted: true }) });
      return (await r.json() as unknown[]).length ? "removed" : "skipped";
    });
  }
  const tally: Record<string, number> = {};
  const queue = [...ops];
  const worker = async () => { while (queue.length) { const op = queue.shift()!; const k = await op(); tally[k] = (tally[k] || 0) + 1; } };
  await Promise.all([worker(), worker(), worker(), worker()]);
  return { changes, ...tally };
}

// ---------- field-name reports (types only, never values) ----------
const MONEY_KEY = /(amount|rent|balance|deposit|fee|total|paid|due|price|cost)/i;
const ENUM_KEY = /(status|type|kind|frequency|method|state|category|period|cycle|recurrence|direction|role)$/i;
function typeOf(key: string, v: unknown): unknown {
  if (v === null || v === undefined) return "null";
  if (Array.isArray(v)) return v.length ? [mergeShapes(v.slice(0, 5).map((x) => typeOf(key, x)))] : ["(empty)"];
  if (typeof v === "object") { const o: Obj = {}; for (const [k, x] of Object.entries(v as Obj)) o[k] = typeOf(k, x); return o; }
  if (typeof v === "number") {
    if (MONEY_KEY.test(key)) return v === 0 ? "int(0)" : (Number.isInteger(v) ? "int" : "decimal") + "(" + String(Math.trunc(Math.abs(v))).length + " digits)";
    return Number.isInteger(v) ? "int" : "decimal";
  }
  if (typeof v === "boolean") return "bool";
  const s = String(v);
  if (/^\d{4}-\d{2}-\d{2}T/.test(s)) return "datetime";
  if (/^\d{4}-\d{2}-\d{2}$/.test(s)) return "date";
  if (/^-?\d+(\.\d+)?$/.test(s)) return "numeric-string";
  if (ENUM_KEY.test(key) && s.length <= 40 && !/@|\d{3}/.test(s)) return "enum:" + s;
  return "string";
}
function mergeShapes(list: unknown[]): unknown {
  const objs = list.filter((x) => x && typeof x === "object" && !Array.isArray(x)) as Obj[];
  if (objs.length !== list.length || !objs.length) { const kinds = [...new Set(list.map((x) => JSON.stringify(x)))].map((x) => JSON.parse(x)); return kinds.length === 1 ? kinds[0] : kinds; }
  const out: Obj = {};
  for (const o of objs) for (const [k, v] of Object.entries(o)) {
    if (!(k in out) || out[k] === "null" || out[k] === "int(0)" || JSON.stringify(out[k]) === '["(empty)"]') out[k] = v;
    else if (JSON.stringify(out[k]) !== JSON.stringify(v) && v !== "null") {
      const a = String(out[k]), b = String(v);
      out[k] = a.startsWith("enum:") && b.startsWith("enum:") ? [...new Set([...a.split(" | "), b])].join(" | ") : out[k];
    }
  }
  return out;
}
function describe(body: unknown) {
  if (Array.isArray(body)) return { list: "(top-level array)", count: body.length, item: mergeShapes(body.slice(0, 5).map((x) => typeOf("", x))) };
  if (body && typeof body === "object") {
    const o = body as Obj, arrays = Object.keys(o).filter((k) => Array.isArray(o[k]));
    const listKey = ["items", "data", "results", "records"].find((k) => arrays.includes(k)) || arrays.sort((a, b) => (o[b] as unknown[]).length - (o[a] as unknown[]).length)[0];
    const paging: Obj = {};
    for (const [k, v] of Object.entries(o)) if (k !== listKey) paging[k] = typeof v === "number" || typeof v === "boolean" ? v : Array.isArray(v) ? `(list of ${v.length})` : typeOf(k, v);
    if (listKey) { const arr = o[listKey] as unknown[]; return { list: listKey, count: arr.length, paging, item: mergeShapes(arr.slice(0, 5).map((x) => typeOf("", x))) }; }
    return { list: null, paging, item: typeOf("", body) };
  }
  return { list: null, note: "not JSON" };
}
