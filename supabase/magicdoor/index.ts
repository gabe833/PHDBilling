async function isStaff(req: Request): Promise<boolean> {
  const auth = req.headers.get("authorization") || "";
  if (!/^Bearer\s+\S+/.test(auth)) return false;
  const apikey = req.headers.get("apikey") || Deno.env.get("SUPABASE_ANON_KEY") || "";
  const r = await fetch(Deno.env.get("SUPABASE_URL")! + "/rest/v1/rpc/is_staff", { method: "POST", headers: { apikey, Authorization: auth, "Content-Type": "application/json" }, body: "{}" });
  return r.ok && (await r.json()) === true;
}
// the hourly schedule (pg_cron) sends a token that only the database knows; it can only run "sync"
async function isSchedule(req: Request): Promise<boolean> {
  const given = req.headers.get("x-md-cron") || "";
  if (given.length < 32) return false;
  const srv = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") || "";
  if (!srv) return false;
  const r = await fetch(Deno.env.get("SUPABASE_URL")! + "/rest/v1/private_settings?select=value&key=eq.md_cron_token", { headers: { apikey: srv, Authorization: "Bearer " + srv } });
  if (!r.ok) return false;
  const rows = await r.json();
  return Array.isArray(rows) && rows.length === 1 && rows[0].value === given;
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: cors });
  if (req.method !== "POST") return json({ error: "POST only" }, 405);
  try {
    const body = await req.json().catch(() => ({})) as Obj;
    const mode = S(body.mode);
    if (mode === "sync" && await isSchedule(req)) return json(await sync());
    if (!(await isStaff(req))) return json({ error: "Not on the team list" }, 403);
    if (mode === "ping") { await mdToken(); return json({ ok: true }); }
    if (mode === "sync") return json(await sync());
    if (mode === "discover") {
      await mdToken();
      const out: Obj = {};
      for (const n of DISCOVER) {
        const p = "/company-app/" + n;
        try { const r = await mdGet(p); out[p] = r.status === 200 ? { status: 200, ...describe(r.body) } : { status: r.status, error: scrub(r.text) }; }
        catch (e) { out[p] = { status: "failed", error: scrub(String(e)) }; }
      }
      return json({ at: new Date().toISOString(), auth: "ok", endpoints: out });
    }
    if (mode === "probe") return json({ at: new Date().toISOString(), endpoints: await probe(MORE) });
    if (mode === "billFile") return json(await billFile(S(body.billId), S(body.fileId)));
    return json({ error: "Unknown mode" }, 400);
  } catch (e) {
    return json({ error: String((e as Error).message || e) }, 502);
  }
});
